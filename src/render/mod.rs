//! Turns a [`Site`] into HTML: the public progress page (written to disk by
//! `build`) and the full app (rendered on request by `serve`).

pub mod assets;
mod components;
mod layout;
pub mod routes;
mod views;

use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};
use maud::Markup;

use crate::domain::Site;
use routes::Ctx;

/// Marks a directory as hourglazs output, so it's safe to wipe on rebuild.
const MARKER: &str = ".hourglazs-output";

pub struct Page {
    /// Path relative to the output root, with `/` separators.
    pub path: String,
    pub html: Markup,
}

/// Every page of the app.
pub fn app_pages(site: &Site, editable: bool) -> Vec<Page> {
    let mut out = Vec::new();
    let mut add = |path: String, render: &dyn Fn(&Ctx) -> Markup| {
        let html = render(&Ctx::at(site, &path, editable));
        out.push(Page { path, html });
    };

    add(routes::HOME.into(), &views::home::page);
    add(routes::TIMELINE.into(), &views::timeline::page);
    for p in &site.projects {
        add(routes::board(&p.slug, None), &|c| views::board::page(c, p, None));
        add(routes::tasks(&p.slug), &|c| views::tasks::page(c, p));
        add(routes::gantt(&p.slug), &|c| views::gantt::page(c, p));
        for (i, n) in p.nodes.iter().enumerate() {
            add(routes::task(&p.slug, &n.task.id), &|c| views::task::page(c, p, i));
            if !n.is_leaf() {
                add(routes::board(&p.slug, Some(&n.task.id)), &|c| views::board::page(c, p, Some(i)));
            }
        }
    }
    out
}

/// One app page by route, or `None` if there is no such page.
pub fn app_page(site: &Site, path: &str, editable: bool) -> Option<Markup> {
    app_pages(site, editable).into_iter().find(|p| p.path == path).map(|p| p.html)
}

/// The public progress page, rendered as if it lived at `path`.
/// A public page by path (`index.html`, `past.html`), under any prefix.
pub fn public_page(site: &Site, path: &str) -> Option<Markup> {
    let ctx = Ctx::at(site, path, false);
    match path.rsplit('/').next()? {
        routes::PUBLIC => Some(views::public::page(&ctx)),
        routes::PUBLIC_PAST => Some(views::past::page(&ctx)),
        _ => None,
    }
}

/// Write the public site into `out`, replacing any previous build there.
/// Writes the public site. Project images are copied from `data_dir`.
pub fn write_public(site: &Site, data_dir: &Path, out: &Path) -> Result<usize> {
    prepare_out_dir(out)?;
    for page in routes::PUBLIC_PAGES {
        let html = public_page(site, page).expect("every public route renders");
        write(&out.join(page), html.0.as_bytes())?;
    }
    for p in site.projects.iter().filter(|p| p.public && !p.image.is_empty()) {
        // Validation already pinned this to one file inside data/images/.
        let bytes = fs::read(data_dir.join(&p.image)).with_context(|| format!("cannot read {}", p.image))?;
        write(&out.join(&p.image), &bytes)?;
    }
    for (path, bytes) in assets::PUBLIC {
        write(&out.join(path), bytes)?;
    }
    write(&out.join(MARKER), b"Generated by hourglazs. This directory is replaced on every build.\n")?;
    Ok(routes::PUBLIC_PAGES.len())
}

fn prepare_out_dir(out: &Path) -> Result<()> {
    if out.exists() {
        let is_ours = out.join(MARKER).exists();
        let is_empty = fs::read_dir(out)?.next().is_none();
        if !is_ours && !is_empty {
            bail!(
                "{} already exists and wasn't created by hourglazs; refusing to overwrite it",
                out.display()
            );
        }
        if is_ours {
            fs::remove_dir_all(out).with_context(|| format!("cannot clear {}", out.display()))?;
        }
    }
    fs::create_dir_all(out).with_context(|| format!("cannot create {}", out.display()))
}

fn write(path: &Path, bytes: &[u8]) -> Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(path, bytes).with_context(|| format!("cannot write {}", path.display()))
}
